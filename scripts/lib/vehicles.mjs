export function motorcycle(m, { x = 0, z = 0, ry = 0, y = 0, c = 'coral', rider = true, person = null } = {}) {
  m.with({ t: [x, y, z], ry }, () => {
    for (const zz of [-0.04, 0.045]) m.with({ t: [0, 0.018, zz], rz: PI / 2 }, () => m.prism('dark', [0, 0], 0.018, -0.005, 0.005, 8, 0, 'kerb'));
    m.box(c, [-0.012, 0.025, -0.035], [0.012, 0.05, 0.035]);
    m.box('dark', [-0.012, 0.05, -0.04], [0.012, 0.058, 0.0]);
    m.beam('dark', [0, 0.02, 0.045], [0, 0.075, 0.035], 0.006);
    m.box('dark', [-0.025, 0.072, 0.03], [0.025, 0.078, 0.036]);
    m.box('lemon', [-0.006, 0.055, 0.04], [0.006, 0.065, 0.045]);
    if (rider && person) {
      person(m, 0, -0.012, 0, { shirt: 'sky', pants: 'navy', pose: 'sit', y: 0.028 });
      m.gem(c, [0, 0.124, -0.015], 0.016, 0.014, 6);
    }
  });
}

