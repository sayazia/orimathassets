// Vehicles at city scale (a person is ~0.1 tall, a car ~0.2 long), facing +z,
// wheels resting on y (0 for standalone objects, G on a ground plate).
const PI = Math.PI;

function wheels(m, xs, zs, r = 0.02, w = 0.01) {
  for (const x of xs) for (const z of zs) m.with({ t: [x, r, z], rz: PI / 2 }, () => m.prism('dark', [0, 0], r, -w, w, 8, 0, 'kerb'));
}
function lights(m, x, zf, zb, y, w = 0.01) {
  for (const s of [-1, 1]) {
    m.box('lemon', [s * x - w, y, zf], [s * x + w, y + 0.01, zf + 0.003]);
    m.box('red', [s * x - w, y, zb - 0.003], [s * x + w, y + 0.01, zb]);
  }
}

